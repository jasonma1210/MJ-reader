//! 续读摘要提示词（P1-13，ai_catch_me_up 无剧透摘要）。
//!
//! 只回看已读内容、不剧透后续；配合调用方按阅读进度定位的「上次位置附近」文本使用。

/// 续读无剧透摘要提示词（`position_label` 用于告知模型这是读到哪里为止的回顾）。
pub fn build_catchup_prompt(position_label: &str, text: &str) -> String {
    format!(
        "你是一名阅读陪伴助手。用户上次读到了{}，请基于以下已读内容生成 100-200 字的无剧透摘要，\
         帮助读者回忆之前的情节、人物与结论。\n\
         反例（禁止出现）：\n\
         1. 不要透露后续尚未读到的内容；\n\
         2. 不要复述原文大段句子，用你自己的话概括；\n\
         3. 不要超过 200 字。\n\n已读内容：\n{}",
        position_label, text
    )
}
